# Methods used in file handling.
# 1. readline() : This method reads a single line from the file.If we want to read multiple lines,we can use a loop.
f=open('myfile.txt','r') #the line by line the whole file.
while(True):
  line=f.readline()
  if not line:
    break
  print(line)
f.close()
# similarly there is readlines() method,which reads all the lines of the file and returns them as a list of strings.

# 2. writeline() : This method writes a sequence of strings to a file.The sequence can be any iterable object,such as a list or a tuple.
f=open('myfile.txt','w')
lines=['line 1\n','line 2\n','line 3\n']
f.writelines(lines)
f.close()
#writelines method does not add newline characters between the strings in the sequence.if newlines are needed ,we can use a loop to write each string separately.
#by using wrtie method.
f=open('myfile.txt','w')
lines=['line1','line2','line3']
for line in lines:
  f.write(line+'\n')
f.close()

# seek() and tell() functions: These functions are used to work with file objects and their positions within a file.These functions are a part of the built-in io
# module,which provides a consistent interface for reading and writing to various file-like objects,such as files,pipes,and in-memory buffers.

# seek() function: This function allows us to move the current position within a file to a specific point. The position is specified in bytes, and you can move either
# forward or backward from the current position.
with open('file.txt','r') as f:
  #move to the 10th byte in the file
  f.seek(10)
  #read the next 5 bytes
  data=f.read(5)
  print(data)

# tell() function: This function returns the current position within the file,in bytes.This can be useful for keeping track of your location within the file or for
# seeking to a specific position relative to the current position.
with open('file.txt','r') as f:
  #move to the 10th byte in the file
  f.seek(10)
  #save the current position
  current_position=f.tell()
  # seek to the saved position
  f.seek(current_position+5)
  #read the next 5 bytes
  data=f.read(5)
  print(data)

