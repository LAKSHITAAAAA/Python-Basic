# opening a file
# Python provides the open() function to open
#a file.It takes two arguments:the name of
#the file and the mode in which the file
#should be opened.The mode can be 'r' for
#reading,'w' for writing,or'a'for appending.

f=open('myfile.txt','r')
#By default,the open() function returns a
#file object that can be used to read from
#or write to the file,depending on the mode.

# Modes in file
#1. read(r):This mode opens the file for reading only and gives an error if the file does not exist.This is the default mode if no mode is passed as a parameter.
#2. write(w):This mode opens the file for writing only and creates a new file if the file does not exist.
#3. append(a):This mode opens the file for appending only and creates a new file if the file does not exist.
#4. create(x):This mode creates a file and gives an error if the file already exists.
#5. text(t):Apart from these modes we also need to specify how the file must be handled.t mode is used to handle text files.t refers to the text mode.
#There is no difference between r and rt or w and wt since text mode is default.
#6. binary(b): used to handle binary files (images,pdfs,etc.)

# reading the contents of the file
text = f.read()
print(text)
f.close() # closing the file

# the contents of the file will not be printed if we open it in write mode

# writing to a file
f=open('myfile.txt','w')
f.write('Hello World')
f.close()

# writing a file will overwrite its contents.
#If you want to append a file instead of overwriting it,you can open it in append mode.
f= open('myfile.txt','a')
